/**
 * Turn an AnalysisResult into a single Markdown document for export.
 *
 * This is the full investigation, not just the postmortem: it keeps the
 * facts/assumptions split, the evidence-against columns and the unverified
 * citations, because those are exactly the parts a reader needs in order to
 * judge how much of this to believe.
 */

const line = (text = '') => `${text}\n`;

function citations(refs, indent = '') {
  if (!refs || refs.length === 0) return `${indent}- _no citation_\n`;
  return refs.map((r) => `${indent}- \`${r.source}\`: "${r.quote}"\n`).join('');
}

export function toMarkdown(result) {
  let md = '';

  md += line(`# Incident investigation: ${result.title || 'Untitled'}`);
  md += line();
  md += line('> Generated by IncidentIQ. Every section below is a draft for human review.');
  md += line('> Hypotheses are candidates, not conclusions.');
  md += line();

  md += line('## Summary');
  md += line();
  md += line(result.summary || '_No summary produced._');
  md += line();

  md += line('## Facts');
  md += line();
  md += line('_Directly supported by the input data._');
  md += line();
  if (result.facts.length) {
    for (const fact of result.facts) {
      md += line(`- **${fact.statement}**`);
      md += citations(fact.evidence, '  ');
    }
  } else {
    md += line('_None extracted._');
  }
  md += line();

  md += line('## Assumptions');
  md += line();
  md += line('_Believed but not proven by the input data._');
  md += line();
  if (result.assumptions.length) {
    for (const a of result.assumptions) {
      md += line(`- **${a.statement}**`);
      md += line(`  - Unproven because: ${a.why_unproven}`);
      md += line(`  - Verify by: ${a.how_to_verify}`);
    }
  } else {
    md += line('_None recorded._');
  }
  md += line();

  md += line('## Timeline');
  md += line();
  if (result.timeline.length) {
    for (const event of result.timeline) {
      const tag = event.inferred ? ' _(inferred)_' : '';
      md += line(`- **${event.timestamp || 'unknown'}** - ${event.description}${tag}`);
      md += citations(event.evidence, '  ');
    }
  } else {
    md += line('_No timeline reconstructed._');
  }
  md += line();

  md += line('## Root-cause hypotheses');
  md += line();
  result.hypotheses.forEach((h, i) => {
    md += line(`### ${i + 1}. ${h.title}`);
    md += line();
    md += line(`**Confidence:** ${h.confidence} - ${h.confidence_reason}`);
    md += line();
    md += line(h.explanation);
    md += line();
    md += line('**Evidence for**');
    md += citations(h.supporting_evidence);
    md += line();
    md += line('**Evidence against**');
    md += citations(h.contradicting_evidence);
    md += line();
    md += line(`**Test that would settle it:** ${h.recommended_test}`);
    md += line();
  });
  if (!result.hypotheses.length) {
    md += line('_None generated._');
    md += line();
  }

  md += line('## Reasoning risks');
  md += line();
  if (result.reasoning_risks.length) {
    for (const risk of result.reasoning_risks) {
      md += line(`### ${risk.bias_name} (\`${risk.bias_id}\`)`);
      md += line();
      md += line(`- **Where it appears:** ${risk.where_it_appears}`);
      md += line(`- **Why it matters:** ${risk.why_it_matters}`);
      md += line(`- **Mitigation:** ${risk.mitigation}`);
      md += line();
    }
  } else {
    md += line('_None flagged._');
    md += line();
  }

  if (result.unverified_citations?.length) {
    md += line('### Unverified citations');
    md += line();
    md += line(
      'The model cited these as evidence, but the quoted text was not found in '
      + 'the source it named. Any claim resting on them is unsupported.',
    );
    md += line();
    md += citations(result.unverified_citations);
    md += line();
  }

  md += line('## Recommended actions');
  md += line();
  if (result.actions.length) {
    for (const action of result.actions) {
      md += line(`- **[${action.priority}]** ${action.step}`);
      md += line(`  - Why: ${action.rationale}`);
      if (action.linked_hypothesis) {
        md += line(`  - Tests: ${action.linked_hypothesis}`);
      }
    }
  } else {
    md += line('_None recommended._');
  }
  md += line();

  md += line('## Open questions');
  md += line();
  if (result.open_questions.length) {
    for (const q of result.open_questions) {
      md += line(`- **${q.question}**`);
      md += line(`  - Matters because: ${q.why_it_matters}`);
    }
  } else {
    md += line('_None recorded._');
  }
  md += line();

  if (result.postmortem_markdown) {
    md += line('---');
    md += line();
    md += line('## Draft postmortem');
    md += line();
    md += line(result.postmortem_markdown);
  }

  return md;
}

/** Trigger a browser download of the investigation as a .md file. */
export function download(result) {
  const blob = new Blob([toMarkdown(result)], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const slug = (result.title || 'incident')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60) || 'incident';

  const anchor = document.createElement('a');
  anchor.href = url;
  anchor.download = `incidentiq-${slug}.md`;
  document.body.append(anchor);
  anchor.click();
  anchor.remove();
  URL.revokeObjectURL(url);
}
